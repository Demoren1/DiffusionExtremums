#!/usr/bin/env bash
# =============================================================================
# collect_targets.sh
# -----------------------------------------------------------------------------
# Запуск полного пайплайна сбора MLP-таргетов для диффузии (Phase 2, Approach B).
#
# Скрипт:
#   1. Активирует conda-окружение `myenv`.
#   2. Формирует и печатает шапку со значениями всех параметров.
#   3. Вызывает CLI `python -m src.scripts.collect_targets` с заданными флагами.
#
# Мульти-GPU: параметр GPUS задаёт список GPU через запятую (напр. "0,1,2,3")
#   или "auto" — использовать все видимые GPU. При >1 GPU корпус разбивается на
#   шарды (по одному процессу на GPU через torch.multiprocessing.spawn), а затем
#   шарды сливаются в стандартный формат вывода. При 0/1 GPU используется
#   последовательный путь на одном устройстве (DEVICE).
#
# Любой параметр можно переопределить через переменную окружения, например:
#     N_DATASETS=500 N_MLP=4 bash scripts/collect_targets.sh
#     DEVICE=cuda LR=1e-3 bash scripts/collect_targets.sh
#     GPUS=0,1,2,3 bash scripts/collect_targets.sh
#     GPUS=auto bash scripts/collect_targets.sh
#
# Запуск:
#     bash scripts/collect_targets.sh
# =============================================================================
set -euo pipefail

# -----------------------------------------------------------------------------
# Активация conda-окружения
# -----------------------------------------------------------------------------
source ~/miniconda3/etc/profile.d/conda.sh
conda activate myenv

# -----------------------------------------------------------------------------
# Параметры корпуса (датасеты и MLP-инициализации)
# -----------------------------------------------------------------------------
# Количество датасетов для генерации и обработки (по умолчанию 500)
N_DATASETS="${N_DATASETS:-500}"
# Количество MLP (разных случайных инициализаций) на каждый датасет (по умолчанию 50)
N_MLP="${N_MLP:-50}"
# Число обучающих точек в каждом датасете
N_TRAIN="${N_TRAIN:-1024}"
# Число тестовых точек в каждом датасете
N_TEST="${N_TEST:-512}"
# Стандартное отклонение шума для всех датасетов
NOISE_STD="${NOISE_STD:-0.1}"
# Базовый seed для сэмплинга конфигураций датасетов
CORPUS_SEED="${CORPUS_SEED:-0}"
# Базовый seed для инициализаций MLP
MLP_SEED_BASE="${MLP_SEED_BASE:-1000}"
# Подмножество семейств функций (через запятую, напр. 'MA,GAUSS'); пусто = все 5
FAMILIES="${FAMILIES:-}"

# -----------------------------------------------------------------------------
# Гиперпараметры обучения MLP
# -----------------------------------------------------------------------------
# Пиковая скорость обучения AdamW
LR="${LR:-3e-3}"
# Максимальное число шагов обучения на один MLP
STEPS="${STEPS:-5000}"
# Минимальное число шагов до разрешения ранней остановки
MIN_STEPS="${MIN_STEPS:-500}"
# Терпение (patience) ранней остановки в шагах
PATIENCE="${PATIENCE:-300}"
# Доля валидационной выборки от обучающей
VAL_FRAC="${VAL_FRAC:-0.1}"
# Weight decay (регуляризация) для AdamW
WEIGHT_DECAY="${WEIGHT_DECAY:-0.0}"
# Устройство torch: 'auto', 'cuda' или 'cpu'. Используется только в
# последовательном (одно-GPU) режиме; в мульти-GPU режиме каждый воркер
# привязывается к своему GPU, а этот параметр игнорируется.
DEVICE="${DEVICE:-cuda}"
# Список GPU для мульти-GPU параллелизма: "auto" (все видимые GPU) или
# идентификаторы через запятую, напр. "0,1,2,3". При >1 GPU корпус шардируется
# по GPU (по одному процессу на GPU) и шарды сливаются в стандартный формат.
# При "auto" на машине без CUDA используется CPU. По умолчанию "auto".
GPUS="${GPUS:-6,7}"

# -----------------------------------------------------------------------------
# Параметры вывода
# -----------------------------------------------------------------------------
# Каталог для сохранения таргетов и метаданных
OUT_DIR="${OUT_DIR:-data/processed/targets}"

# -----------------------------------------------------------------------------
# Шапка: печать значений параметров перед запуском
# -----------------------------------------------------------------------------
echo "============================================================"
echo " Сбор MLP-таргетов (Phase 2, Approach B)"
echo "------------------------------------------------------------"
echo "  Корпус:"
echo "    n_datasets   = ${N_DATASETS}"
echo "    n_mlp        = ${N_MLP}"
echo "    n_train      = ${N_TRAIN}"
echo "    n_test       = ${N_TEST}"
echo "    noise_std    = ${NOISE_STD}"
echo "    corpus_seed  = ${CORPUS_SEED}"
echo "    mlp_seed_base= ${MLP_SEED_BASE}"
echo "    families     = '${FAMILIES}' (пусто = все)"
echo "  Обучение:"
echo "    lr           = ${LR}"
echo "    steps        = ${STEPS}"
echo "    min_steps    = ${MIN_STEPS}"
echo "    patience     = ${PATIENCE}"
echo "    val_frac     = ${VAL_FRAC}"
echo "    weight_decay = ${WEIGHT_DECAY}"
echo "    device       = ${DEVICE}  (только для одно-GPU режима)"
echo "  GPU:"
echo "    gpus         = ${GPUS}  (auto = все видимые; >1 GPU -> параллелизм)"
echo "  Вывод:"
echo "    out_dir      = ${OUT_DIR}"
echo "============================================================"

# -----------------------------------------------------------------------------
# Сборка команды вызова CLI
# -----------------------------------------------------------------------------
CMD=(python -m src.scripts.collect_targets
    --n-datasets "${N_DATASETS}"
    --n-mlp "${N_MLP}"
    --n-train "${N_TRAIN}"
    --n-test "${N_TEST}"
    --noise-std "${NOISE_STD}"
    --corpus-seed "${CORPUS_SEED}"
    --mlp-seed-base "${MLP_SEED_BASE}"
    --lr "${LR}"
    --steps "${STEPS}"
    --min-steps "${MIN_STEPS}"
    --patience "${PATIENCE}"
    --val-frac "${VAL_FRAC}"
    --weight-decay "${WEIGHT_DECAY}"
    --device "${DEVICE}"
    --gpus "${GPUS}"
    --out-dir "${OUT_DIR}"
)

# Флаг --families передаётся только если задано непустое значение
if [[ -n "${FAMILIES}" ]]; then
    CMD+=(--families "${FAMILIES}")
fi

# -----------------------------------------------------------------------------
# Запуск
# -----------------------------------------------------------------------------
echo "Запуск: ${CMD[*]}"
exec "${CMD[@]}"
